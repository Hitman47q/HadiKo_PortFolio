export function getInitialLang() {
  try {
    const saved = localStorage.getItem('lang')
    if (saved === 'en' || saved === 'ar') return saved
  } catch { /* storage blocked */ }
  const browserLang = navigator.language || ''
  return browserLang.startsWith('ar') ? 'ar' : 'en'
}
